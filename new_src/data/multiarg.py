RAW_PATH = Path(__file__).with_name("heldout_v2_raw.json")

_BUILDERS = {"WIRE": wire_c2o, "STO": standing_order_p2r, "TRV": travel_o2i}


def _load_heldout() -> list:
    """The generated held-out multi-argument pairs, or an empty list before generation."""
    if not RAW_PATH.exists():
        return []
    raw = json.loads(RAW_PATH.read_text(encoding="utf-8"))
    bases = {entry["base_id"]: Base(entry["base_id"], entry["customer_id"], entry["customer_name"],
                                    entry["identity_fact"]) for entry in raw.get("bases", [])}
    pairs = []
    for code, builder in _BUILDERS.items():
        for entry in raw.get(code, []):
            fields = {key: value for key, value in entry.items() if key != "base_id"}
            pairs.append(builder(bases[entry["base_id"]], **fields))
    return pairs


MULTIARG_HELDOUT = _load_heldout()
